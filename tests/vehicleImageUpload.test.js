import assert from 'node:assert/strict';
import { prepareVehicleImageOrder } from '../src/services/vehicleImageUpload.js';
import { VEHICLE_IMAGE_MAX_BYTES } from '../src/utils/imageCompressor.js';

const file = name => new File([new Uint8Array(1000)], name, { type: 'image/webp' });
const existing = { isExisting: true, url: '/legacy-photo.jpg' };
const first = file('primera.webp'), second = file('segunda.webp');
const cache = new WeakMap();
const calls = [];
let failSecond = true;
const upload = async (url, options) => {
    const photo = options.body.get('files');
    calls.push(photo.name);
    assert.equal(url, '/api/admin/upload');
    assert.equal(options.method, 'POST');
    assert.equal(options.headers.Authorization, 'Bearer fake');
    assert.equal(options.headers['Content-Type'], undefined);
    assert.deepEqual([...options.body.keys()], ['files']);
    assert.ok(photo.size <= VEHICLE_IMAGE_MAX_BYTES);
    if (photo.name === 'segunda.webp' && failSecond) return { ok: false, json: async () => ({ message: 'Fallo simulado' }) };
    return { ok: true, json: async () => ({ uploadedFiles: [{ url: `https://res.cloudinary.com/qa/image/upload/v1/autosporting-cars/${photo.name}` }] }) };
};
const config = { token: 'fake', cache, fetchImpl: upload };
await assert.rejects(prepareVehicleImageOrder([existing, first, second], config), /Fallo simulado/);
failSecond = false;
const order = await prepareVehicleImageOrder([second, existing, first], config);
assert.deepEqual(calls, ['primera.webp', 'segunda.webp', 'segunda.webp']);
assert.equal(order[0].endsWith('/segunda.webp'), true);
assert.equal(order[1], existing.url);
assert.equal(order[2].endsWith('/primera.webp'), true);
await prepareVehicleImageOrder([first, second], config);
assert.equal(calls.length, 3);
assert.deepEqual(await prepareVehicleImageOrder([], config), []);
const replacement = file('primera.webp');
await prepareVehicleImageOrder([replacement], config);
assert.equal(calls.length, 4, 'A replacement File must be uploaded even if it has the same filename.');
const before = calls.length;
await assert.rejects(prepareVehicleImageOrder([first, { isExisting: true }], config), /existente/);
await assert.rejects(prepareVehicleImageOrder(Array(21).fill(first), config), /20 fotos/);
await assert.rejects(prepareVehicleImageOrder([new File([new Uint8Array(VEHICLE_IMAGE_MAX_BYTES + 1)], 'grande.webp')], config), /lista para subir/);
await assert.rejects(prepareVehicleImageOrder([first], { ...config, token: '' }), /sesión/);
assert.equal(calls.length, before, 'Invalid selections must fail before any request.');
await assert.rejects(prepareVehicleImageOrder([file('invalid.webp')], { token: 'fake', fetchImpl: async () => ({ ok: true, json: async () => ({ uploadedFiles: [{ url: 'javascript:alert(1)' }] }) }) }), /dirección válida/);
let largeRequests = 0;
const largeFiles = Array.from({ length: 4 }, (_, index) => new File([new Uint8Array(VEHICLE_IMAGE_MAX_BYTES)], `hq-${index}.webp`, { type: 'image/webp' }));
const largeOrder = await prepareVehicleImageOrder(largeFiles, { token: 'fake', fetchImpl: async (_, options) => {
    largeRequests++;
    assert.equal([...options.body.values()].length, 1);
    assert.ok(options.body.get('files').size < 2 * 1024 * 1024);
    return { ok: true, json: async () => ({ uploadedFiles: [{ url: `https://res.cloudinary.com/qa/image/upload/v1/autosporting-cars/hq-${largeRequests}.webp` }] }) };
} });
assert.equal(largeRequests, 4);
assert.equal(largeOrder.length, 4);
console.log('PASS image upload: bounded per-photo requests, order, retry cache, validation and large selections.');
